"""About the data: source, licence, cleaning steps, responsible use and limitations."""
import streamlit as st

from explorer.data_loader import to_csv_text
from explorer.models import MIN_RECORDS
from ui_common import DATASET_PAGE, LICENCE_URL, escape_markdown, get_data, source_info

data = get_data()
report = data.report
info = source_info()

st.title("About the data")

st.header("Source and licence")
st.markdown(
    f"All language names, codes, alternative names and locations come from the "
    f"[AUSTLANG dataset]({DATASET_PAGE}), published by the Australian Institute of "
    f"Aboriginal and Torres Strait Islander Studies (AIATSIS) under a "
    f"[Creative Commons Attribution 4.0 licence]({LICENCE_URL}). "
    "No language content in this app was written or generated by AI."
)
st.markdown(
    "**Attribution:** AUSTLANG dataset, Australian Institute of Aboriginal and Torres "
    "Strait Islander Studies (AIATSIS), CC BY 4.0. Cleaned and reformatted for this app."
)
if info:
    st.caption(
        f"This copy was downloaded on {escape_markdown(info.get('downloaded', 'an unrecorded date'))}. "
        "AUSTLANG is a live dataset that AIATSIS updates regularly, so a newer download may differ."
    )
else:
    st.caption(
        "AUSTLANG is a live dataset that AIATSIS updates regularly. "
        "The download date of this copy is recorded in data/README.md."
    )

st.header("How the data was cleaned")
verdict = "meets" if report.meets_minimum else "is below"
st.markdown(
    f"The file **{escape_markdown(report.source)}** has **{report.rows_read:,}** rows. "
    f"After cleaning, **{report.rows_kept:,}** language varieties remain, which {verdict} "
    f"the project minimum of {MIN_RECORDS} records."
)

columns_text = ", ".join(escape_markdown(column) for column in report.columns_used.values())
ignored_text = ", ".join(escape_markdown(column) for column in report.columns_ignored) or "none"
if report.has_state_column:
    state_step = (
        "**Took states and territories** from AUSTLANG's state_territory column, and "
        "estimated them from the coordinates for records where it was blank."
    )
else:
    state_step = (
        "**Estimated each variety's state or territory** from its coordinates, because "
        "this file has no state column."
    )
st.markdown(
    f"""
1. **Read the file** as {escape_markdown(report.encoding)} text and trimmed extra spaces from every value.
2. **Matched the columns** the app needs: {columns_text}. Not used: {ignored_text}.
3. **Removed {report.missing_code_or_name:,} rows** that had no language code or no name.
4. **Removed {report.duplicate_codes:,} repeated codes**, keeping the first copy of each.
5. **Checked the coordinates.** {report.no_coordinates:,} varieties have none, and {report.invalid_coordinates:,} had values that were not numbers or fell outside Australia. These varieties stay searchable but are not mapped.
6. **Split the alternative names** (comma- or pipe-separated) and removed blanks, repeats and copies of the main name, leaving {report.alternative_names_found:,} alternative names.
7. {state_step}
8. **Checked the links.** Only ordinary web addresses were kept; {report.unsafe_links_removed:,} were removed.
"""
)
st.download_button(
    "Download the cleaned data (CSV)",
    data=to_csv_text(data.languages),
    file_name="austlang_cleaned.csv",
    mime="text/csv",
)

st.header("Using this information respectfully")
st.markdown(
    """
- Each location is a single approximate point from AUSTLANG. It is not a boundary or a map of Country.
- Names and spellings vary. For information about a particular language, contact the relevant community or language centre.
- The app shows only published, openly licensed information. It holds no restricted cultural knowledge, and no images, voices or names of people.
- The app stores nothing about you: there are no accounts, and searches are not saved.
"""
)

st.header("Limitations")
st.markdown(
    """
- Varieties without coordinates can be searched but not mapped or included in distance results.
- States estimated from coordinates use simplified borders, so points near a border may be placed in the wrong state.
- Distances are straight lines to an approximate point, not travel distances.
- The data is a snapshot of a live dataset, so counts will change when the file is updated.
"""
)
